import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { hash, options, runBatch } from '../scripts/batch_mermaid.mjs';

const skill = fileURLToPath(new URL('../', import.meta.url));
test('real browser: batch, errors, resume, options and legacy entrypoints', { timeout: 120000 }, async () => {
  const temp = await fs.mkdtemp(path.join(os.tmpdir(), 'mermaid-integration-'));
  console.log(`Visual review artifacts retained: ${temp}`);
  const file = path.join(temp, '日本語.md');
  const good = '# 取引設計\n\n## 注文\n```mermaid\nflowchart LR\nA["注文受付"] --> B{"残高確認"}\nB -->|承認| C["発注完了"]\n```\n\n## 通知\n~~~mermaid\nsequenceDiagram\nparticipant A as 利用者\nparticipant B as 注文サービス\nA->>B: 注文依頼\nB-->>A: 受付完了\n~~~\n';
  await fs.writeFile(file, good + '\n## 壊れた図\n```mermaid\nflowchart LR\nA[\n```\n');
  const base = options(['--out-dir', path.join(temp, 'mixed'), '--format', 'png,svg', file]);
  const normalInputs = await Promise.all([1, 2, 3].map(async n => {
    const name = path.join(temp, `document-${n}.md`);
    await fs.writeFile(name, good);
    return name;
  }));
  const normal = await runBatch({ ...base, inputs: normalInputs, outDir: path.join(temp, 'six-diagrams') });
  assert.equal(normal.success, true, JSON.stringify(normal.errors));
  assert.equal(normal.diagrams.length, 6);
  assert.equal(normal.browserLaunches, 1);
  const first = await runBatch(base);
  assert.equal(first.browserLaunches, 1, JSON.stringify(first.errors));
  assert.equal(first.success, false);
  assert.deepEqual(first.diagrams.map(d => d.parse.status), ['success', 'success', 'failed']);
  assert.equal(first.diagrams[2].parse.kind, 'syntax');
  assert.equal(first.diagrams[2].render.status, 'not_run');
  assert.equal(first.diagrams[0].artifacts.length, 2);
  await fs.writeFile(file, good + '\n## 修正済み\n```mermaid\nflowchart TD\nA["価格取得"] --> B["条件判定"]\n```\n');
  const second = await runBatch({ ...base, resume: first.reportPath, only: [`${file}#3`] });
  assert.equal(second.success, true, JSON.stringify(second));
  assert.equal(second.browserLaunches, 1);
  assert.deepEqual(second.diagrams.map(d => !!d.parse.reused), [true, true, false]);
  const cached = await runBatch({ ...base, resume: second.reportPath });
  assert.equal(cached.success, true);
  assert.equal(cached.browserLaunchAttempts, 0);
  await fs.writeFile(cached.diagrams[0].artifacts[0].path, 'corrupted');
  const repaired = await runBatch({ ...base, resume: cached.reportPath });
  assert.equal(repaired.success, true);
  assert.equal(repaired.browserLaunches, 1);
  assert.equal(repaired.diagrams[0].parse.reused, true);
  assert.equal(repaired.diagrams[0].render.reused, undefined);
  const partial = await runBatch({ ...base, outDir: path.join(temp, 'partial'), only: [`${file}#3`] });
  assert.equal(partial.success, false);
  assert.equal(partial.diagrams[0].parse.status, 'not_run');
  const transparent = await runBatch({ ...base, outDir: path.join(temp, 'transparent'), background: 'transparent', width: 640 });
  assert.equal(transparent.success, true);
  const svg = await fs.readFile(transparent.diagrams[0].artifacts.find(a => a.format === 'svg').path, 'utf8');
  assert.match(svg, /background-color: transparent/);
  assert.match(svg, /注文受付/);
  const config = path.join(temp, 'browser.json');
  await fs.writeFile(config, JSON.stringify({ executablePath: path.join(temp, 'missing-browser') }));
  const env = await runBatch({ ...base, outDir: path.join(temp, 'environment'), puppeteerConfig: config });
  assert.equal(env.success, false);
  assert.equal(env.browserLaunchAttempts, 1);
  assert.equal(env.browserLaunches, 0);
  assert.ok(env.diagrams.every(d => d.parse.kind === 'environment' && d.render.status === 'not_run'));
  const blocker = path.join(temp, 'not-a-directory');
  await fs.writeFile(blocker, 'block');
  const outputError = await runBatch({ ...base, outDir: blocker });
  assert.equal(outputError.success, false);
  assert.equal(outputError.errors[0].kind, 'environment');
  assert.equal(outputError.browserLaunchAttempts, 0);
  const badOutputDir = path.join(temp, 'late-output-error');
  const badArtifact = path.join(badOutputDir, `${hash(`${file}#1`).slice(0, 16)}-1.png`);
  await fs.mkdir(badArtifact, { recursive: true });
  const late = await runBatch({ ...base, outDir: badOutputDir });
  assert.equal(late.diagrams[0].parse.status, 'success');
  assert.equal(late.diagrams[0].render.kind, 'environment');
  await fs.rmdir(badArtifact);
  const recovered = await runBatch({ ...base, outDir: badOutputDir, resume: late.reportPath });
  assert.equal(recovered.success, true);
  assert.ok(recovered.diagrams.every(d => d.parse.reused));
  assert.equal(recovered.diagrams[0].render.reused, undefined);
  const badLayout = path.join(temp, 'layout.json');
  await fs.writeFile(badLayout, JSON.stringify({ maxTextSize: 1 }));
  const renderFailure = await runBatch({ ...base, outDir: path.join(temp, 'render-error'), config: badLayout });
  assert.equal(renderFailure.diagrams[0].parse.status, 'success');
  assert.equal(renderFailure.diagrams[0].render.kind, 'render');
  const single = path.join(temp, 'single.mmd');
  await fs.writeFile(single, 'flowchart LR\nA["開始"] --> B["終了"]');
  const legacyParse = spawnSync(process.execPath, [path.join(skill, 'scripts/validate_mermaid.mjs'), single], { encoding: 'utf8' });
  assert.equal(legacyParse.status, 0, legacyParse.stderr + legacyParse.stdout);
  const legacyRender = spawnSync('bash', [path.join(skill, 'scripts/render_mermaid.sh'), single, path.join(temp, 'legacy.svg')], { encoding: 'utf8' });
  assert.equal(legacyRender.status, 0, legacyRender.stderr + legacyRender.stdout);
  assert.match(await fs.readFile(path.join(temp, 'legacy.svg'), 'utf8'), /終了/);
  console.log('3 Markdown documents / 6 diagrams: 1 browser; mixed 3 diagrams: 1 browser; repair 1 diagram: 1 browser; unchanged resume: 0 browsers. Legacy: 2 commands / 2 browsers.');
});
